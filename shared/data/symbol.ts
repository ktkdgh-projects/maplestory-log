// "아케인심볼 : 소멸의 여로" 같은 이름에서 표와 지역을 찾는다. 표에 없는 새 지역이면 null
export function findSymbolTable(symbolName: string): { table: SymbolTable, region: string } | null {
  const region = symbolName.split(':').at(-1)?.trim() ?? ''
  const table = symbolName.includes('아케인') ? ARCANE_SYMBOL : AUTHENTIC_SYMBOL
  return table.meso[region] ? { table, region } : null
}

// from레벨 → to레벨에 드는 메소와 심볼 개수. 지금 레벨에서 시작하면 이미 모은 성장치만큼 심볼을 덜 쓴다
export function symbolCost(symbolName: string, from: number, to: number, currentLevel: number, growth: number) {
  const found = findSymbolTable(symbolName)
  if (!found) return null
  const { table, region } = found
  let meso = 0
  let symbols = from === currentLevel ? -growth : 0
  for (let lv = Math.max(from, 1); lv < Math.min(to, table.maxLevel); lv++) {
    meso += table.meso[region]![lv - 1]!
    symbols += table.growth[lv - 1]!
  }
  return { meso, symbols: Math.max(symbols, 0) }
}

// 지금 모은 성장치로 메소만 내면 올라갈 수 있는 레벨. 성장치는 다음 레벨 요구량을 넘겨서도 쌓인다
export function reachableSymbolLevel(symbolName: string, level: number, growth: number): number {
  const found = findSymbolTable(symbolName)
  if (!found) return level
  let reached = level
  let left = growth
  while (reached < found.table.maxLevel && left >= found.table.growth[reached - 1]!) {
    left -= found.table.growth[reached - 1]!
    reached++
  }
  return reached
}
